suma=0 #iniciacion del contador suma en 0
n=int(input("¿cantidad de valores a procesar?")) #cantidad de valores que se van ingresar
#estructura repetitiva while
for x in range(n):
    valor=float(input("ingresar valor: "))
    suma=suma+valor
#impresion de la suma
print("suma de los valores ingresados: ",suma)

